def build_individual_user_prompt(
    nickname: str,
    role: str,
    bazi_data: Dict[str, Any],
    mbti_data: Dict[str, Any]
) -> str:
    payload = {
        "nickname": nickname,
        "work_role": role or "ไม่ระบุตำแหน่ง",
        "bazi_structure": bazi_data,
        "mbti_structure": mbti_data,
    }
    return (
        "จงวิเคราะห์ข้อมูลโครงสร้างด้านล่างนี้ และสร้างคู่มือการทำงานส่วนบุคคลตาม JSON Schema ที่กำหนด:\n\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}"
    )


